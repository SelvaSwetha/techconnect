import type { EnquiryRecord } from '../store/enquiryStore.ts'
import type { Field } from '../validation.ts'
import { BRAND, escapeHtml, formatTimestamp, layout } from './layout.ts'

export const ADMIN_SUBJECT = 'New Hiring Enquiry – TechzConnect'

const SOURCE_LABEL: Record<EnquiryRecord['source'], string> = {
  home: 'Homepage – hiring brief',
  industries: 'Industries page',
  'employer-enquiry': 'Employer Enquiry page',
}

/** Display order and labels. Fields a form does not collect (or the user left empty) are simply not shown. */
const ROWS: [Field, string][] = [
  ['fullName', 'Full Name'],
  ['email', 'Work Email'],
  ['phone', 'Phone Number'],
  ['company', 'Company Name'],
  ['service', 'Service Required'],
  ['industry', 'Industry'],
  ['roles', 'Role(s) Hiring For'],
  ['location', 'Hiring Location(s)'],
  ['positions', 'Number of Positions'],
  ['hires', 'Number of Hires'],
  ['timeline', 'Hiring Timeline'],
]

export interface RenderedEmail {
  subject: string
  html: string
  text: string
}

const formatSize = (bytes: number): string => (bytes >= 1024 * 1024 ? `${(bytes / 1024 / 1024).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1024))} KB`)

export function renderAdminEmail(record: EnquiryRecord, opts: { logoUrl?: string } = {}): RenderedEmail {
  const f = record.fields
  const rows: [string, string][] = ROWS.filter(([k]) => f[k]).map(([k, label]) => [label, f[k] as string])
  if (record.attachment) rows.push(['Job Description', `${record.attachment.originalName} (${formatSize(record.attachment.size)}) – attached to this email`])
  rows.push(['Submitted', formatTimestamp(new Date(record.createdAt))])
  rows.push(['Source', SOURCE_LABEL[record.source]])
  rows.push(['Reference', record.reference])

  const cell = 'padding:10px 12px;border-bottom:1px solid #e5e7eb;font-family:Arial,Helvetica,sans-serif;font-size:14px;vertical-align:top;'
  const table = rows
    .map(([label, value]) => {
      const v = label === 'Work Email' ? `<a href="mailto:${escapeHtml(value)}" style="color:#d60000;text-decoration:none;">${escapeHtml(value)}</a>` : escapeHtml(value)
      return `<tr><td width="38%" style="${cell}color:#6b7280;font-weight:600;">${escapeHtml(label)}</td><td style="${cell}color:#111827;word-break:break-word;">${v}</td></tr>`
    })
    .join('')
  const message = f.message
    ? `<p style="margin:22px 0 8px;font-weight:700;color:#111827;">Hiring Requirements / Message</p>
<div style="background-color:#f9fafb;border:1px solid #e5e7eb;border-left:4px solid #ff0000;border-radius:6px;padding:14px 16px;font-size:14px;line-height:1.6;color:#111827;white-space:pre-wrap;word-break:break-word;">${escapeHtml(f.message)}</div>`
    : ''

  const html = layout({
    title: ADMIN_SUBJECT,
    preheader: `${f.fullName ?? 'Someone'}${f.company ? ` from ${f.company}` : ''} submitted a hiring enquiry.`,
    logoUrl: opts.logoUrl,
    bodyHtml: `<h1 style="margin:0 0 8px;font-size:22px;line-height:1.3;color:#000000;">New Hiring Enquiry Received</h1>
<p style="margin:0 0 20px;color:#4b5563;">A new hiring request has been submitted through the ${BRAND} website. The details are below.</p>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="border:1px solid #e5e7eb;border-bottom:0;border-radius:6px;">${table}</table>
${message}`,
    footerHtml: `<strong style="color:#374151;">${BRAND}</strong><br>Hiring Enquiry Notification<br>This is an automated notification generated by the ${BRAND} website.`,
  })

  const text = [
    'New Hiring Enquiry Received',
    '',
    `A new hiring request has been submitted through the ${BRAND} website.`,
    '',
    ...rows.map(([l, v]) => `${l}: ${v}`),
    ...(f.message ? ['', 'Hiring Requirements / Message:', f.message] : []),
    '',
    '--',
    BRAND,
    'Hiring Enquiry Notification',
    `This is an automated notification generated by the ${BRAND} website.`,
  ].join('\n')

  return { subject: ADMIN_SUBJECT, html, text }
}
