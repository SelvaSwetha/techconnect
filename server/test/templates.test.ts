import assert from 'node:assert/strict'
import { test } from 'node:test'
import { renderAdminEmail } from '../src/templates/adminEmail.ts'
import { renderUserEmail } from '../src/templates/userEmail.ts'
import { contentHash } from '../src/store/enquiryStore.ts'
import type { EnquiryRecord } from '../src/store/enquiryStore.ts'

const record = (): EnquiryRecord => {
  const fields = {
    fullName: 'Asha <b>Verma</b>', email: 'asha@acme-test.example', phone: '+91 98765 43210', company: 'Acme "Test" & Co',
    service: 'Executive Search', positions: '3', message: 'Need CTO.\n<script>alert(1)</script>',
  }
  return {
    reference: 'TC-20261112-ABC234', createdAt: '2026-11-12T14:32:00.000Z', source: 'home', idempotencyKey: 'k', consent: false,
    contentHash: contentHash('home', fields), fields, notifications: { admin: 'pending', acknowledgement: 'pending' },
  }
}

test('admin email has the required subject, heading, every field, timestamp and footer', () => {
  const m = renderAdminEmail(record())
  assert.equal(m.subject, 'New Hiring Enquiry – TechzConnect')
  for (const s of ['New Hiring Enquiry Received', 'Full Name', 'Work Email', 'Phone Number', 'Company Name', 'Service Required', 'Number of Positions',
    'Hiring Requirements / Message', '12 Nov 2026, 14:32 UTC', 'TC-20261112-ABC234', 'Hiring Enquiry Notification',
    'This is an automated notification generated by the TechzConnect website.']) {
    assert.ok(m.html.includes(s), `html missing: ${s}`)
  }
  assert.ok(m.text.includes('Hiring Enquiry Notification') && m.text.includes('Company Name: Acme "Test" & Co'))
})

test('user-supplied content is HTML-escaped in the email (no injected markup)', () => {
  const html = renderAdminEmail(record()).html
  assert.ok(!html.includes('<script>') && !html.includes('<b>Verma'))
  assert.ok(html.includes('&lt;script&gt;') && html.includes('Acme &quot;Test&quot; &amp; Co'))
  assert.ok(!renderUserEmail(record()).html.includes('<b>Verma'))
})

test('acknowledgement has the required subject and text, the reference, and promises no response time', () => {
  const m = renderUserEmail(record())
  assert.equal(m.subject, 'We Have Received Your Hiring Enquiry – TechzConnect')
  assert.ok(m.text.startsWith('Hello Asha <b>Verma</b>,'))
  assert.ok(m.text.includes('Your enquiry reference: TC-20261112-ABC234'))
  assert.ok(m.text.includes('We have successfully received your hiring enquiry. Our team will review your requirements and contact you regarding the next steps.'))
  assert.ok(m.text.includes('Best regards,\nTechzConnect Team'))
  assert.ok(!/\b(within|24|48|hours|business days|shortly|soon)\b/i.test(m.text))
})

test('optional https logo is used, otherwise a text wordmark', () => {
  assert.ok(renderAdminEmail(record(), { logoUrl: 'https://cdn.example/logo.png' }).html.includes('<img src="https://cdn.example/logo.png"'))
  assert.ok(!renderAdminEmail(record()).html.includes('<img'))
})
